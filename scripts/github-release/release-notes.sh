#!/bin/bash
#
# Описание релиза для GitHub. Печатает готовый markdown в stdout.
#
#   scripts/github-release/release-notes.sh 9.0.1              # посмотреть, что получится
#   scripts/github-release/release-notes.sh 9.0.1 > notes.md   # так вызывает workflow
#
# Состав: что нового (секция версии из release-history.md) → какой файл скачать → что нажать
# при первом запуске → как обновиться. Страница релиза — место, где скачивают программу,
# поэтому списка коммитов и прочих подробностей здесь нет.
#
# Сети и gh не требует: собирается целиком из файлов репозитория.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HISTORY="$ROOT/scripts/github-release/release-history.md"
VERSION="${1:-}"

[ -n "$VERSION" ] || { echo "Использование: release-notes.sh <версия>" >&2; exit 1; }
[ -f "$HISTORY" ] || { echo "Нет файла scripts/github-release/release-history.md" >&2; exit 1; }

# ── Что нового: секция «## [версия]» до следующего «## [» ─────────────────────
# \r в конце строк отбрасывается: на Windows файл может прийти с окончаниями CRLF.
BODY="$(awk -v head="## [$VERSION]" '
  { sub(/\r$/, "") }
  index($0, head) == 1 { found = 1; next }
  found && /^## \[/    { exit }
  found                { print }
' "$HISTORY")"

# Пустые строки в начале секции убираются; в конце их уже съела подстановка $(...).
BODY="$(printf '%s\n' "$BODY" | sed -e '/./,$!d')"

if [ -z "$BODY" ]; then
  echo "В release-history.md нет непустой секции «## [${VERSION}]»" >&2
  exit 1
fi

echo "## Что нового"
echo
printf '%s\n' "$BODY"
echo
# Каждый абзац ниже — одна строка: GitHub показывает перенос строки в описании релиза как разрыв.
cat <<EOF
## Скачать

| Система | Файл |
|---|---|
| Windows 10 и 11 | \`BackupApp-$VERSION-windows-x64.exe\` |
| macOS на Apple Silicon (M1 и новее) | \`BackupApp-$VERSION-macos-arm64.dmg\` |
| macOS на Intel | \`BackupApp-$VERSION-macos-x64.dmg\` |
| Linux | \`BackupApp-$VERSION-linux-x64.tar.gz\` |

Python ставить не нужно: все, что нужно программе, уже внутри файла.

## Первый запуск

Программа не подписана платным сертификатом, поэтому при первом запуске система попросит подтверждение. Это нужно сделать один раз.

**Windows.** Программа не устанавливается: скачанный файл и есть программа. Положите его в постоянную папку, например в «Документы», и запустите. Появится синее окно «Система Windows защитила ваш компьютер»:

1. Нажмите **«Подробнее»**.
2. Нажмите **«Выполнить в любом случае»**.

**macOS.** Откройте образ, перетащите BackupApp в папку «Программы» и запустите ее оттуда. Появится окно о том, что macOS не может проверить программу:

1. Нажмите **«Готово»**.
2. Откройте **Системные настройки → Конфиденциальность и безопасность** и прокрутите вниз до раздела **«Безопасность»**.
3. Рядом с сообщением о BackupApp нажмите **«Все равно открыть»** и подтвердите.

**Linux.** Распакуйте архив и запустите программу:

\`\`\`bash
tar -xzf BackupApp-$VERSION-linux-x64.tar.gz
./BackupApp
\`\`\`

Подходят Ubuntu 22.04 и новее, Debian 12, Fedora 36 и другие системы того же возраста и новее.

## Обновление

Настройки и история копирования хранятся отдельно от программы и при обновлении сохраняются.

1. Закройте программу: щелкните правой кнопкой по значку в трее и выберите **«Выход»**.
2. Запустите новую версию:
   - **Windows**: запустите новый файл. Если был включен автозапуск, включите заново переключатель **«Автозапуск при входе в систему»** на странице «Настройки»: автозапуск помнит путь к файлу, а у новой версии другое имя. Старый файл после этого можно удалить.
   - **macOS**: перетащите новую BackupApp в «Программы» с заменой.
   - **Linux**: замените файл \`BackupApp\` новым.
EOF
